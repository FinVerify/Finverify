/**
 * generate-world-map.mjs
 * 
 * Fetches Natural Earth 110m land GeoJSON and converts it to pre-computed
 * SVG path strings using Mercator projection. Outputs a TypeScript data file
 * that can be imported directly by the GlobalTransactionMonitor component.
 * 
 * Usage: node scripts/generate-world-map.mjs
 */

const GEOJSON_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";

// SVG viewBox dimensions
const WIDTH = 1000;
const HEIGHT = 500;

// Mercator projection — clamp latitude to avoid infinity at poles
function mercatorProject(lon, lat) {
  const clampedLat = Math.max(-85, Math.min(85, lat));
  const x = (lon + 180) * (WIDTH / 360);
  const latRad = clampedLat * Math.PI / 180;
  const mercN = Math.log(Math.tan(Math.PI / 4 + latRad / 2));
  const y = HEIGHT / 2 - (WIDTH * mercN / (2 * Math.PI));
  return [Math.round(x * 100) / 100, Math.round(y * 100) / 100];
}

function coordsToPath(ring) {
  if (ring.length < 3) return "";
  const parts = [];
  for (let i = 0; i < ring.length; i++) {
    const [x, y] = mercatorProject(ring[i][0], ring[i][1]);
    parts.push(i === 0 ? `M${x},${y}` : `L${x},${y}`);
  }
  parts.push("Z");
  return parts.join(" ");
}

function geometryToSvgPaths(geometry) {
  const paths = [];
  if (geometry.type === "Polygon") {
    for (const ring of geometry.coordinates) {
      const d = coordsToPath(ring);
      if (d) paths.push(d);
    }
  } else if (geometry.type === "MultiPolygon") {
    for (const polygon of geometry.coordinates) {
      for (const ring of polygon) {
        const d = coordsToPath(ring);
        if (d) paths.push(d);
      }
    }
  }
  return paths;
}

async function main() {
  console.log("Fetching Natural Earth 110m land GeoJSON...");
  const res = await fetch(GEOJSON_URL);
  if (!res.ok) throw new Error(`Failed to fetch: ${res.status}`);
  const geojson = await res.json();
  
  console.log(`Processing ${geojson.features.length} features...`);
  
  const allPaths = [];
  for (const feature of geojson.features) {
    const paths = geometryToSvgPaths(feature.geometry);
    allPaths.push(...paths);
  }
  
  console.log(`Generated ${allPaths.length} SVG paths`);
  
  // Combine smaller paths and output as TypeScript
  const output = `/**
 * Auto-generated world map SVG paths from Natural Earth 110m land data.
 * Mercator projection, viewBox 0 0 ${WIDTH} ${HEIGHT}.
 * Generated by scripts/generate-world-map.mjs
 * DO NOT EDIT MANUALLY.
 */

export const WORLD_MAP_PATHS: string[] = ${JSON.stringify(allPaths, null, 0)};

export const WORLD_MAP_VIEWBOX = "${WIDTH} ${HEIGHT}";
`;

  const fs = await import("fs");
  const path = await import("path");
  const outPath = path.join(
    path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, "$1"),
    "..",
    "components",
    "workspace",
    "worldMapData.ts"
  );
  
  fs.writeFileSync(outPath, output, "utf-8");
  console.log(`Written to ${outPath}`);
}

main().catch(console.error);
